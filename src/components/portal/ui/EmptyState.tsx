"use client";

import { HTMLAttributes, forwardRef } from "react";
import Link from "next/link";
import { Button } from "./Button";

export interface EmptyStateProps extends HTMLAttributes<HTMLDivElement> {
  icon?: React.ReactNode;
  title: string;
  description?: string;
  action?: {
    label: string;
    href: string;
    variant?: "primary" | "secondary" | "outline";
  };
  size?: "sm" | "md" | "lg";
}

export const EmptyState = forwardRef<HTMLDivElement, EmptyStateProps>(
  (
    {
      icon,
      title,
      description,
      action,
      size = "md",
      className = "",
      children,
      ...props
    },
    ref
  ) => {
    const sizes = {
      sm: "py-8",
      md: "py-16",
      lg: "py-24",
    };

    const iconSizes = {
      sm: "w-10 h-10",
      md: "w-16 h-16",
      lg: "w-20 h-20",
    };

    return (
      <div
        ref={ref}
        className={`text-center ${sizes[size]} ${className}`}
        {...props}
      >
        {icon && (
          <div className={`mx-auto mb-4 text-slate-300 dark:text-slate-600 ${iconSizes[size]}`}>
            {icon}
          </div>
        )}
        <h3 className="text-lg font-medium text-slate-900 dark:text-white mb-1">{title}</h3>
        {description && (
          <p className="text-slate-500 dark:text-slate-400 mb-6 max-w-md mx-auto">{description}</p>
        )}
        {action && (
          <Link href={action.href}>
            <Button variant={action.variant || "primary"} size="md">
              {action.label}
            </Button>
          </Link>
        )}
        {children}
      </div>
    )
  }
);

EmptyState.displayName = "EmptyState";

